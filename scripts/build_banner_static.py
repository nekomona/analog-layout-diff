"""Generate the README's reduced-motion SVG from assets/banner.svg.

Run with --check to detect a stale static copy without changing files.
"""
import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    source = (root / 'assets/banner.svg').read_text(encoding='utf-8')
    static, count = re.subn(r'(?m)^[ \t]*<animate\b[^>]*/>[ \t]*\n', '', source)
    if count != 1:
        raise ValueError('Expected exactly one self-contained banner animation')
    static = ('<!-- Generated by scripts/build_banner_static.py; edit banner.svg. -->\n'
              + static.replace('beneath breathing green', 'beneath solid green'))
    ET.fromstring(static)
    target = root / 'assets/banner-static.svg'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != static:
            raise SystemExit('Static banner is stale; run python scripts/build_banner_static.py')
        print('Static banner matches the animated source')
    else:
        target.write_text(static, encoding='utf-8', newline='\n')
        print('Generated assets/banner-static.svg')


if __name__ == '__main__':
    main()
